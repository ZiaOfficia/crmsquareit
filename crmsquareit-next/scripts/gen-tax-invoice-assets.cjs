// Regenerates src/lib/tax-invoice-assets.ts. Run from the app folder: node scripts/gen-tax-invoice-assets.cjs
const fs = require("fs");
const b = (f) => fs.readFileSync(f).toString("base64");
let o = `/* GENERATED by scripts/gen-tax-invoice-assets.cjs — do not edit by hand.
   Tax invoice PDF assets, embedded so the PDF never depends on which folder the server runs from.
   Sources: src/lib/fonts/montserrat/Montserrat-{400,500,600,700}.ttf (Latin + ₹ subset, OFL),
   public/invoice/logo.jpg and public/invoice/signature.png (taken from src/pdfinvoice). */
`;
for (const w of [400, 500, 600, 700]) o += `export const MONTSERRAT_${w} = "data:font/ttf;base64,${b(`src/lib/fonts/montserrat/Montserrat-${w}.ttf`)}";\n`;
o += `export const INVOICE_LOGO_BASE64 = "${b("public/invoice/logo.jpg")}";\n`;
o += `export const INVOICE_SIGNATURE_BASE64 = "${b("public/invoice/signature.png")}";\n`;
fs.writeFileSync("src/lib/tax-invoice-assets.ts", o);
console.log("wrote src/lib/tax-invoice-assets.ts");
